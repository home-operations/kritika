func TestDefaults(t *testing.T) {
	defaults := map[string]reflect.Value{}
	walk(reflect.ValueOf(Defaults()), "", func(l leaf) { defaults[l.path] = l.value })
	for path, want := range golden {
		t.Run(path, func(t *testing.T) {
			got, ok := defaults[path]
			if !ok {
				t.Fatalf("no field at tuning.%s", path)
			}
			if !reflect.DeepEqual(got.Interface(), want) {
				t.Fatalf("default = %#v, want %#v", got.Interface(), want)
			}
		})
	}
}

// TestDefaultsAllPinned: a field cannot be added without its default
// pinned in golden.
func TestDefaultsAllPinned(t *testing.T) {
	walk(reflect.ValueOf(Values{}), "", func(l leaf) {
		if _, ok := golden[l.path]; !ok {
			t.Errorf("tuning.%s (%s) has no row in golden", l.path, l.env)
		}
	})
}
