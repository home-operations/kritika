#!/bin/sh
set -eu

# The aqua registry the runner installs repository tools from: the release
# below, whose registry.yaml the runner fetches and checks against the
# SHA-256 this records beside it. The release has no assets, so the file
# comes from its tag.
# renovate: datasource=github-releases depName=aquaproj/aqua-registry
version=v4.578.0

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
curl -fsSL --retry 3 -o "$tmp" "https://raw.githubusercontent.com/aquaproj/aqua-registry/${version}/registry.yaml"
if command -v sha256sum >/dev/null 2>&1; then
	sum=$(sha256sum "$tmp" | cut -d' ' -f1)
else
	sum=$(shasum -a 256 "$tmp" | cut -d' ' -f1)
fi
cat >internal/aqua/release.go <<EOF
// Code generated by scripts/aqua-registry.sh. DO NOT EDIT.

package aqua

// RegistryVersion is the aqua-registry release whose registry.yaml the
// runner fetches, and registrySHA256 the SHA-256 that file must have.
const (
	RegistryVersion = "${version}"
	registrySHA256  = "${sum}"
)
EOF
